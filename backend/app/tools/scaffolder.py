"""Application & Website Scaffolding Tool for Forge (Coding Agent).

Enables autonomous scaffolding of verified web and microservice project templates
strictly inside approved sandboxed storage/projects/ directories with automated
Git safety checkpointing prior to generation.
"""
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from app.agents.orchestrator import orchestrator
from app.core.config import settings
from app.core.logging import get_audit_logger, logger
from app.services.git_service import git_service
from app.tools.filesystem import SecurityViolationError, sandboxed_fs

audit_logger = get_audit_logger()


class ProjectScaffoldError(Exception):
    """Raised when project generation fails or violates directory constraints."""
    pass


class ApplicationScaffolder:
    """Safely scaffolds application projects inside storage/projects/."""

    SUPPORTED_TEMPLATES = {
        "fastapi_microservice": "Lightweight async API service with health checks & tests",
        "nextjs_landing": "Next.js modern responsive dark landing page with Tailwind CSS",
        "python_cli": "Command-line utility with argparse and structured logging",
    }

    def list_templates(self) -> Dict[str, str]:
        return self.SUPPORTED_TEMPLATES

    def scaffold_project(
        self,
        project_name: str,
        template: str = "fastapi_microservice",
        description: str = "Automated application generated by NEXUS Forge agent.",
    ) -> Dict[str, Any]:
        """Scaffolds a new project inside storage/projects/ with automated Git safety snapshot."""
        clean_name = re.sub(r"[^a-zA-Z0-9_\-]+", "_", project_name.lower()).strip("_")
        if not clean_name:
            raise ProjectScaffoldError("Invalid project name.")

        if template not in self.SUPPORTED_TEMPLATES:
            raise ProjectScaffoldError(
                f"Unsupported template '{template}'. Supported: {list(self.SUPPORTED_TEMPLATES.keys())}"
            )

        # 1. Create Git safety snapshot prior to filesystem changes
        checkpoint_msg = f"NEXUS Safety Checkpoint: Scaffold project '{clean_name}' ({template})"
        checkpoint_result = git_service.create_checkpoint(checkpoint_msg)

        project_rel_dir = f"projects/{clean_name}"
        created_files: List[str] = []

        # 2. Generate template files
        if template == "fastapi_microservice":
            files = {
                f"{project_rel_dir}/main.py": (
                    '"""FastAPI Microservice Scaffolding."""\n'
                    'from fastapi import FastAPI\n\n'
                    f'app = FastAPI(title="{clean_name.title()}", description="{description}")\n\n'
                    '@app.get("/health")\n'
                    'async def health():\n'
                    '    return {"status": "ok", "service": "' + clean_name + '"}\n'
                ),
                f"{project_rel_dir}/requirements.txt": "fastapi>=0.110.0\nuvicorn>=0.30.0\npydantic>=2.7.0\npytest>=8.0.0\nhttpx>=0.27.0\n",
                f"{project_rel_dir}/tests/test_api.py": (
                    'import pytest\n'
                    'from httpx import ASGITransport, AsyncClient\n'
                    'from main import app\n\n'
                    '@pytest.mark.asyncio\n'
                    'async def test_health():\n'
                    '    transport = ASGITransport(app=app)\n'
                    '    async with AsyncClient(transport=transport, base_url="http://test") as client:\n'
                    '        r = await client.get("/health")\n'
                    '        assert r.status_code == 200\n'
                    '        assert r.json()["status"] == "ok"\n'
                ),
                f"{project_rel_dir}/README.md": (
                    f"# {clean_name.title()}\n\n"
                    f"{description}\n\n"
                    f"- **Scaffolded by**: NEXUS Forge Agent\n"
                    f"- **Template**: `{template}`\n"
                    f"- **Timestamp**: {datetime.now(timezone.utc).isoformat()}\n"
                ),
            }

        elif template == "nextjs_landing":
            files = {
                f"{project_rel_dir}/package.json": (
                    '{\n'
                    f'  "name": "{clean_name}",\n'
                    '  "version": "0.1.0",\n'
                    '  "private": true,\n'
                    '  "scripts": { "dev": "next dev", "build": "next build", "start": "next start" },\n'
                    '  "dependencies": { "next": "14.2.35", "react": "^18", "react-dom": "^18" }\n'
                    '}\n'
                ),
                f"{project_rel_dir}/src/app/page.tsx": (
                    f'export default function Page() {{\n'
                    f'  return (\n'
                    f'    <main className="min-h-screen bg-slate-950 text-slate-100 flex items-center justify-center p-8">\n'
                    f'      <div className="max-w-xl text-center space-y-4">\n'
                    f'        <h1 className="text-3xl font-bold tracking-tight">{clean_name.title()}</h1>\n'
                    f'        <p className="text-slate-400">{description}</p>\n'
                    f'      </div>\n'
                    f'    </main>\n'
                    f'  );\n'
                    f'}}\n'
                ),
                f"{project_rel_dir}/README.md": (
                    f"# {clean_name.title()} Landing Page\n\n"
                    f"{description}\n\n"
                    f"- **Framework**: Next.js 14 App Router\n"
                    f"- **Scaffolded by**: NEXUS Forge Agent\n"
                ),
            }

        else:  # python_cli
            files = {
                f"{project_rel_dir}/cli.py": (
                    '#!/usr/bin/env python3\n'
                    'import argparse\n'
                    'import sys\n\n'
                    'def main():\n'
                    f'    parser = argparse.ArgumentParser(description="{description}")\n'
                    '    parser.add_argument("--version", action="version", version="0.1.0")\n'
                    '    args = parser.parse_args()\n'
                    f'    print("Executing {clean_name} CLI...")\n\n'
                    'if __name__ == "__main__":\n'
                    '    main()\n'
                ),
                f"{project_rel_dir}/README.md": (
                    f"# {clean_name.title()} CLI Utility\n\n"
                    f"{description}\n"
                ),
            }

        # Write all files through sandboxed filesystem
        for rel_file_path, content in files.items():
            sandboxed_fs.write_text_file(rel_file_path, content, requires_approval=False)
            created_files.append(rel_file_path)

        orchestrator.log_activity(
            agent_id="coding_agent",
            action="Project Scaffolded",
            details=f"Generated {len(created_files)} files in storage/{project_rel_dir} ({template})",
            status="completed",
        )
        audit_logger.info(f"Project scaffolded successfully: {project_rel_dir} ({len(created_files)} files)")

        return {
            "project_name": clean_name,
            "template": template,
            "directory": project_rel_dir,
            "created_files": created_files,
            "git_checkpoint": checkpoint_result.get("commit_hash"),
            "status": "ready",
        }


app_scaffolder = ApplicationScaffolder()
